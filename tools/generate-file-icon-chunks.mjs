import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const directory = 'src/utils/file-icon-chunks'
const maximumBytes = 32 * 1024
const check = process.argv.includes('--check')
const outputs = new Map()
const json = value => JSON.stringify(value) + '\n'

for (const [pack, prefix] of [['material', 'file'], ['catppuccin', 'catppuccin']]) {
  const artwork = JSON.parse(await fs.readFile(path.join(root, `src/utils/${prefix}-icon-artwork.json`), 'utf8'))
  const manifest = JSON.parse(await fs.readFile(path.join(root, `src/utils/${prefix}-icon-manifest.json`), 'utf8'))
  const groups = new Map()
  for (const id of Object.keys(artwork).sort()) {
    const pair = pack === 'material' && id.endsWith('_light') && Object.hasOwn(artwork, id.slice(0, -6)) ? id.slice(0, -6)
      : pack === 'catppuccin' ? id.replace(/^(?:latte|mocha)-/, '') : id
    const group = groups.get(pair) ?? {}
    group[id] = artwork[id]
    groups.set(pair, group)
  }
  const buckets = []
  let bucket = {}
  for (const key of [...groups.keys()].sort()) {
    const group = groups.get(key)
    if (Buffer.byteLength(json(group)) > maximumBytes) throw new Error(`Icon variants exceed ${maximumBytes} bytes: ${pack}/${key}`)
    if (Buffer.byteLength(json({ ...bucket, ...group })) > maximumBytes) { buckets.push(bucket); bucket = {} }
    Object.assign(bucket, group)
  }
  if (Object.keys(bucket).length) buckets.push(bucket)
  const index = {}, imports = []
  for (const [number, entries] of buckets.entries()) {
    const file = `${pack}-${String(number).padStart(2, '0')}.json`
    outputs.set(`${directory}/${file}`, json(entries))
    for (const id of Object.keys(entries)) index[id] = number
    imports.push(`  () => import('./${file}').then(module => module.default),`)
  }
  const ids = Object.fromEntries(Object.keys(index).sort().map(id => [id, index[id]]))
  outputs.set(`${directory}/${pack}.ts`, `// Generated by tools/generate-file-icon-chunks.mjs; keep original artwork as the source.\nexport const iconChunks: Readonly<Record<string, number>> = ${JSON.stringify(ids)}\nexport const genericIcon = ${JSON.stringify(manifest.file)}\nexport const genericLightIcon = ${JSON.stringify(manifest.light?.file ?? manifest.file)}\nexport const loadChunks = [\n${imports.join('\n')}\n]\n`)
}

const existing = await fs.readdir(path.join(root, directory)).catch(error => { if (error.code === 'ENOENT') return []; throw error })
const stale = existing.filter(file => !outputs.has(`${directory}/${file}`))
if (check && stale.length) throw new Error(`Unexpected generated icon chunks: ${stale.join(', ')}`)
if (!check) await fs.mkdir(path.join(root, directory), { recursive: true })
for (const [file, content] of outputs) {
  if (check) {
    if (await fs.readFile(path.join(root, file), 'utf8') !== content) throw new Error(`Regenerate file icon chunks: ${file}`)
  } else await fs.writeFile(path.join(root, file), content)
}
if (!check) for (const file of stale) await fs.rm(path.join(root, directory, file))
