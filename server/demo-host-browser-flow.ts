import assert from 'node:assert/strict'
import path from 'node:path'
import type { Page } from 'playwright-core'

export async function verifyDemoHost(page: Page, width: number, screenshots: string): Promise<void> {
  const openMenu = async () => { await page.getByRole('button', { name: '메뉴', exact: true }).click(); return page.locator('[data-header-menu]') }
  let menu = await openMenu()
  for (const label of ['원격 데스크톱', '원격 브라우저', '서버 파일 탐색기', '예약 작업', '업데이트', '계정 관리', '설정']) assert.equal(await menu.getByText(label, { exact: true }).count(), 1, label)
  for (const label of ['Android', '시스템 자원', '채팅', '데이터베이스', 'Commit']) assert.equal(await menu.getByText(label, { exact: true }).count(), 0, label)
  assert.equal(await menu.locator('[data-workspace-row="profile"]').count(), 1)
  for (const hint of ['Alt+E', 'Alt+S', 'Ctrl+U']) assert.equal(await menu.getByText(hint, { exact: true }).count(), 1, hint)
  await page.screenshot({ path: path.join(screenshots, `menu-${width}.png`) })
  await page.keyboard.press('Escape')
  await menu.waitFor({ state: 'detached' })
  await page.locator('header').getByRole('button', { name: '시스템 자원 보기', exact: true }).click()
  const stats = page.getByRole('dialog', { name: '시스템 자원', exact: true })
  await stats.getByText('Demo GPU', { exact: true }).waitFor()
  await page.screenshot({ path: path.join(screenshots, `system-${width}.png`) })
  await stats.getByRole('button', { name: '닫기', exact: true }).click()
  if (width === 390) await page.evaluate('globalThis.demoVideoFrame = VideoFrame; globalThis.VideoFrame = undefined')
  menu = await openMenu(); await menu.getByText('원격 데스크톱', { exact: true }).click()
  const desktop = page.getByRole('dialog', { name: '원격 데스크톱', exact: true })
  await desktop.locator('.desktop-status[data-connected="true"]').waitFor()
  if (width === 390) {
    await page.waitForFunction(`document.querySelector('.desktop-video:is(video)')?.videoWidth === 960`)
    await page.evaluate('globalThis.demoCanvasTrack = document.querySelector("video.desktop-video").srcObject.getVideoTracks()[0]')
  } else assert.equal(await desktop.locator('canvas.desktop-video').evaluate(element => element.width), 960)
  await page.screenshot({ path: path.join(screenshots, `desktop-host-${width}.png`) })
  await desktop.locator('.desktop-stage').press('a')
  await page.waitForFunction(`globalThis.demoWorkspace.getState('desktop-note', '').endsWith('a')`)
  await desktop.getByRole('button', { name: '원격 데스크톱 설정', exact: true }).click()
  await desktop.getByText('공유 화면', { exact: true }).first().waitFor()
  await desktop.getByRole('button', { name: '설정 닫기', exact: true }).click()
  await page.locator('.mobile-dock [data-dock-item="database"]').click()
  await desktop.waitFor({ state: 'detached' })
  const database = page.getByRole('dialog', { name: '데이터베이스', exact: true })
  await database.waitFor({ state: 'visible' })
  const closeDatabase = database.getByRole('button', { name: '닫기', exact: true })
  assert.equal(await closeDatabase.evaluate(element => {
    const bounds = element.getBoundingClientRect()
    return element.contains(element.ownerDocument.elementFromPoint(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2))
  }), true, 'the database controls remain reachable after leaving remote desktop')
  await closeDatabase.click()
  if (width === 390) {
    assert.equal(await page.evaluate('globalThis.demoCanvasTrack.readyState'), 'ended')
    await page.evaluate('globalThis.VideoFrame = globalThis.demoVideoFrame')
  }
  menu = await openMenu(); await menu.getByText('예약 작업', { exact: true }).click()
  const schedules = page.getByRole('dialog', { name: '예약 작업', exact: true })
  await schedules.getByText('문서 변경 요약 · Demo', { exact: true }).waitFor()
  await schedules.getByRole('button', { name: '문서 변경 요약 · Demo 터미널 세션', exact: true }).click()
  const session = page.getByRole('dialog', { name: '문서 변경 요약 · Demo', exact: true })
  await session.getByRole('button', { name: '실행', exact: true }).click()
  await page.waitForFunction(`globalThis.demoWorkspace.getState('host-schedules', [])[0]?.lastRun`)
  await session.getByRole('button', { name: '닫기', exact: true }).click()
  await schedules.getByRole('button', { name: '닫기', exact: true }).first().click()
  menu = await openMenu(); await menu.getByText('업데이트', { exact: true }).click()
  const updates = page.getByRole('dialog', { name: '업데이트', exact: true })
  await updates.getByText('Remote desktop · Demo', { exact: true }).waitFor()
  await updates.getByRole('button', { name: '닫기', exact: true }).click()
  menu = await openMenu(); await menu.getByText('계정 관리', { exact: true }).click()
  const admin = page.getByRole('dialog', { name: '계정 관리', exact: true })
  await admin.getByRole('checkbox', { name: 'member@example.test 원격 데스크톱', exact: true }).waitFor()
  await admin.locator('summary').filter({ hasText: /^Mewlink 계정 접근/ }).click()
  await admin.getByText('Demo guest', { exact: true }).waitFor()
  assert.equal(await admin.getByRole('button', { name: 'Demo guest 접근 승인', exact: true }).isVisible(), true)
  assert.equal(await admin.getByRole('button', { name: 'Demo guest 접근 요청 거절', exact: true }).isVisible(), true)
  assert.equal(await admin.getByRole('alert').count(), 0)
  await admin.getByRole('button', { name: '닫기', exact: true }).click()
  menu = await openMenu(); await menu.getByText('Mewlink', { exact: true }).click()
  const mewlink = page.getByRole('dialog', { name: 'Mewlink', exact: true })
  await mewlink.getByText('Mew Demo', { exact: true }).waitFor()
  assert.equal(await mewlink.getByRole('alert').count(), 0)
  await mewlink.getByRole('button', { name: '닫기', exact: true }).click()
  await page.locator('.mobile-dock [data-dock-item="debugger"]').click()
  await page.getByText('initializeDemo (simulated)', { exact: true }).waitFor()
  await page.getByRole('button', { name: '다음 줄', exact: true }).click()
  await page.waitForFunction(`globalThis.demoWorkspace.getState('debug-session:/demo/mew-playground', {}).stopRevision === 2`)
  await page.locator('[data-workspace-panel="debugger"]').getByRole('button', { name: '닫기', exact: true }).click()
}
